"""The upload pack is a deliverable, so it gets checked like one.

YouTube rejects a chapter list that breaks its rules, and it truncates a title
that is too long. Both are silent failures - you only find out after publishing -
so the pack is generated by code and verified here: the chapters clear the
ten-second floor, the first starts at zero, the titles fit, and every chapter
time lands on a section that actually exists in the film.
"""
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import upload_pack  # noqa: E402

BRIEF = json.loads((ROOT / "video_studio" / "briefs" / "review-ai-code.json").read_text(encoding="utf-8"))
FILM = json.loads((ROOT / "docs" / "media" / "review-ai-code-plan.json").read_text(encoding="utf-8"))


class TheChaptersPlayByYouTubesRules(unittest.TestCase):
    def setUp(self):
        self.pack = upload_pack.build(BRIEF, FILM)

    def test_there_are_at_least_three(self):
        self.assertGreaterEqual(len(self.pack["chapters"]), 3)

    def test_the_first_starts_at_zero(self):
        self.assertEqual(self.pack["chapters"][0]["start"], 0.0)

    def test_every_chapter_is_ten_seconds_or_more(self):
        chapters = self.pack["chapters"]
        for index, chapter in enumerate(chapters):
            end = (chapters[index + 1]["start"] if index + 1 < len(chapters)
                   else self.pack["duration_seconds"])
            self.assertGreaterEqual(end - chapter["start"], 10.0,
                                    "chapter %r is %.1f s" % (chapter["heading"], end - chapter["start"]))

    def test_every_chapter_starts_on_a_section(self):
        starts = {round(float(shot["start"]), 3) for shot in FILM["shots"]} | {0.0}
        for chapter in self.pack["chapters"]:
            self.assertIn(round(chapter["start"], 3), starts)

    def test_a_short_section_is_kept_in_the_chapter_it_falls_in(self):
        """Nine sections cannot be nine chapters. The ones folded in are named."""
        folded = [heading for chapter in self.pack["chapters"] for heading in chapter.get("also") or []]
        self.assertTrue(folded, "no section was merged, so some chapter is under ten seconds")
        named = {upload_pack.sentence(s.get("heading", "")) for s in BRIEF["sections"]}
        for heading in folded:
            self.assertIn(heading, named)


class ThePackFitsTheBoxes(unittest.TestCase):
    def setUp(self):
        self.pack = upload_pack.build(BRIEF, FILM)

    def test_the_first_title_fits_a_phone(self):
        self.assertLessEqual(len(self.pack["titles"][0]), upload_pack.SHORT_TITLE)

    def test_every_title_fits_youtube(self):
        for title in self.pack["titles"]:
            self.assertLessEqual(len(title), upload_pack.MAX_TITLE)

    def test_the_pack_offers_a_question(self):
        """A question opens a loop; at least one option should ask one."""
        self.assertTrue(any(title.endswith("?") for title in self.pack["titles"]))

    def test_the_description_fits_and_names_the_chapters(self):
        text = self.pack["description"]
        self.assertLessEqual(len(text), upload_pack.MAX_DESCRIPTION)
        for chapter in self.pack["chapters"]:
            self.assertIn(chapter["time"], text)

    def test_the_tags_fit_the_budget(self):
        self.assertLessEqual(sum(len(tag) + 1 for tag in self.pack["tags"]), upload_pack.MAX_TAGS)

    def test_the_briefs_own_tags_come_first(self):
        for index, tag in enumerate(BRIEF["tags"]):
            self.assertEqual(self.pack["tags"][index], tag)

    def test_no_tag_is_a_stopword_pair(self):
        for tag in self.pack["tags"]:
            words = tag.split()
            self.assertFalse(all(word in upload_pack.STOPWORDS for word in words), tag)

    def test_the_description_opens_with_the_films_own_first_line(self):
        first_line = BRIEF["sections"][0]["lines"][0]["text"]
        self.assertTrue(self.pack["description"].startswith(first_line),
                        self.pack["description"][:120])


class ThePackIsWrittenOut(unittest.TestCase):
    def test_markdown_carries_the_chapters_and_the_titles(self):
        pack = upload_pack.build(BRIEF, FILM)
        markdown = upload_pack.to_markdown(pack)
        for chapter in pack["chapters"]:
            self.assertIn("%s %s" % (chapter["time"], chapter["heading"]), markdown)
        for title in pack["titles"]:
            self.assertIn(title, markdown)

    def test_the_delivered_pack_matches_the_delivered_film(self):
        delivered = ROOT / "docs" / "media" / "review-ai-code-upload-pack.md"
        self.assertTrue(delivered.is_file(), "the pack is missing from docs/media")
        text = delivered.read_text(encoding="utf-8")
        pack = upload_pack.build(BRIEF, FILM)
        for chapter in pack["chapters"]:
            self.assertIn(chapter["time"], text)


if __name__ == "__main__":
    unittest.main()
