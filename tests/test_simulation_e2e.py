"""Offline end-to-end simulation: dashboard queue -> CEO -> specialists -> reviewed output.

All web research and local-model responses are synthetic mocks. No internet request,
paid API, Ollama process, Docker container, or external action is used.
"""
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

import agent
import dashboard
import orchestrate


class EndToEndSimulationTests(unittest.TestCase):
    def test_submitted_task_reaches_reviewed_output_without_live_services(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            tasks_path = root / "tasks.json"
            config_path = root / "config.json"
            workspace = root / "workspace"
            outputs = root / "outputs"
            logs = root / "logs"
            workspace.mkdir(parents=True)
            config_path.write_text(
                json.dumps({
                    "model": {
                        "enabled": True,
                        "model": "simulation-only",
                        "base_url": "http://127.0.0.1:11434/v1/chat/completions",
                        "max_output_tokens": 900,
                        "timeout_seconds": 1
                    },
                    "runner": {"max_tasks_per_cycle": 3}
                }),
                encoding="utf-8",
            )

            role_calls = []
            research_calls = []

            def simulated_research(topic, **kwargs):
                research_calls.append(topic)
                metadata = {
                    "topic": topic,
                    "engine": "SIMULATION ONLY",
                    "queries": [topic],
                    "result_count": 1,
                    "pages_attempted": 1,
                    "pages_fetched": 1,
                    "verified": False,
                    "note": "Synthetic fixture; no network page was fetched."
                }
                sources = [{
                    "title": "Synthetic test fixture",
                    "url": "https://example.test/simulation-fixture",
                    "snippet": "Synthetic evidence used only to test wiring."
                }]
                return metadata, sources

            def simulated_model_response(url, body, timeout):
                messages = body.get("messages", [])
                system_text = messages[0].get("content", "") if messages else ""
                user_text = messages[1].get("content", "") if len(messages) > 1 else ""
                role_calls.append({
                    "system": system_text[:160],
                    "user": user_text[:500],
                    "timeout": timeout,
                    "model": body.get("model"),
                })

                if "Act as the CEO of Agent HQ" in user_text:
                    answer = json.dumps({
                        "assignments": [{
                            "agent_id": "AGENT-09",
                            "task": "Create a concise structured draft and list assumptions."
                        }]
                    })
                elif "You are specialist " + reviewer_name + "." in system_text:
                    answer = (
                        "# Simulated Quality Review\n\n"
                        "- Required output exists: PASS\n"
                        "- Limitations disclosed: PASS\n"
                        "- Live sources or actions falsely claimed: NO\n\n"
                        "OVERALL QUALITY GATE: PASS\n"
                    )
                else:
                    answer = (
                        "# Simulated Specialist Deliverable\n\n"
                        "This output was generated by a deterministic test fixture, not a real AI model.\n\n"
                        "## Assumptions and limitations\n"
                        "- External research is synthetic and must not be relied on as factual evidence.\n"
                    )
                return {"choices": [{"message": {"content": answer}}]}

            reviewer = orchestrate.dispatch.find_role("AGENT-08")
            self.assertIsNotNone(reviewer)
            reviewer_name = reviewer["name"]

            with (
                patch.object(dashboard, "TASKS", tasks_path),
                patch.object(agent, "TASKS", tasks_path),
                patch.object(agent, "CONFIG", config_path),
                patch.object(agent, "WORKSPACE", workspace),
                patch.object(agent, "OUTPUTS", outputs),
                patch.object(agent, "LOGS", logs),
                patch.object(orchestrate, "ROOT", root),
                patch.object(orchestrate, "WORKSPACE", workspace),
                patch.object(orchestrate, "run_builtin_tools", return_value=[]),
                patch.object(orchestrate.dispatch, "ROOT", root),
                patch.object(orchestrate.dispatch, "FEEDBACK_DIR", workspace / "training" / "feedback"),
                patch.object(orchestrate.dispatch, "collect_web_research", side_effect=simulated_research),
                patch.object(orchestrate.dispatch, "render_research_markdown",
                             return_value="# SIMULATED RESEARCH\n\nSynthetic test fixture only."),
                patch.object(orchestrate.dispatch, "post_local_model", side_effect=simulated_model_response),
            ):
                task_id = dashboard.enqueue_task(
                    "Simulation: concise AI agents explainer",
                    "draft",
                    "Create a concise explainer draft about how a local-first AI agent system routes tasks. "
                    "Label assumptions and limitations; do not claim live research or actions.",
                )
                self.assertEqual(task_id, "TASK-0001")
                before = json.loads(tasks_path.read_text(encoding="utf-8"))
                self.assertEqual(before[0]["status"], "pending")

                processed = agent.cycle()
                self.assertEqual(processed, 1)

                after = json.loads(tasks_path.read_text(encoding="utf-8"))
                self.assertEqual(after[0]["id"], task_id)
                self.assertTrue(after[0].get("output_file"))

                manifest_path = workspace / "orchestration" / ("task-" + task_id) / "pipeline-status.json"
                self.assertTrue(manifest_path.is_file())
                manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
                self.assertEqual(
                    after[0]["status"], "completed",
                    "Unexpected queue status; pipeline manifest follows:\n" + json.dumps(manifest, indent=2)
                )
                self.assertTrue(after[0].get("output_file"))

                result_file = root / after[0]["output_file"]
                self.assertTrue(result_file.is_file(), f"Missing result: {result_file}")
                result_text = result_file.read_text(encoding="utf-8")
                self.assertIn("CEO delegation plan", result_text)
                self.assertIn("Specialist deliverables", result_text)
                self.assertIn("SIMULATED", result_text.upper())
                self.assertEqual(manifest["delegation_mode"], "ceo_model_delegation")
                self.assertEqual(manifest["pipeline"][-1]["agent_id"], "AGENT-08")
                self.assertEqual(manifest["quality_gate"], "pass")
                self.assertGreaterEqual(len(role_calls), 3)
                self.assertGreaterEqual(len(research_calls), 1)
                progress_path = manifest_path.with_name("pipeline-progress.json")
                self.assertTrue(progress_path.is_file())
                progress = json.loads(progress_path.read_text(encoding="utf-8"))
                self.assertEqual(progress["phase"], "Pipeline complete")
                self.assertEqual(progress["completed_stages"], progress["total_stages"])


if __name__ == "__main__":
    unittest.main()
