/**
 * The stickman: monochrome line artwork for the existing rig.
 *
 * Same skeleton, same IK, same animation — a different pen. Everything here is
 * drawn from the solved bone positions, so the figure keeps its planted feet,
 * its weight shift and its lip-sync without any of that being re-implemented.
 *
 * ## Why it looks like this
 *
 * A stick figure is easy to draw badly. The difference between "cheap" and
 * "professional" is almost entirely four habits, and all four are enforced here:
 *
 * 1. **Tapered strokes.** A uniform line reads as a diagram. Every limb is
 *    thickest at the body and thinnest at the extremity, which is what a brush
 *    does and what makes the figure look drawn rather than plotted.
 * 2. **Visible joints.** Small discs at every articulation stop limbs from
 *    reading as sticks glued at the middle; they are the visual equivalent of a
 *    socket.
 * 3. **Line boil.** A sub-pixel jitter that differs every frame, so straight
 *    lines breathe the way hand-inked ones do. Off by default because it costs
 *    determinism in the *look* (not the pose); `boil: 1` turns it on.
 * 4. **Restraint.** Two values only: paper and ink. There is no gradient, no
 *    shadow, no third colour. `resolveInk` refuses a colour outright unless an
 *    accent is explicitly enabled, so "black and white" cannot drift.
 *
 * ## Copyright
 *
 * There is no asset here: a circle, a line and five joints, generated by this
 * file. Nothing is traced, imported, licensed or attributable.
 */

import { VISEMES } from './rig.mjs';
import { taperedLimb } from './body.mjs';

/**
 * Paper and ink. Both are exactly neutral grey: a warm or cool tint is a colour,
 * and `resolveInk` refuses one. Not #FFF and not #000 either — pure white blooms
 * on an OLED phone and pure black crushes against a dark UI.
 */
export const INK = {
  paper: '#F2F2F2',
  ink: '#121212',
  /**
   * Cloth tone: a neutral grey between paper and ink.
   *
   * A cloak filled with the same ink as the limbs swallows them — a black arm on
   * a black cape is not a drawing, it is a blob. A light grey restores
   * the separation without introducing a hue, so the figure stays monochrome and
   * still has depth.
   */
  cape: '#787878',
  /**
   * The one accent, for the cape lining.
   *
   * The reference the channel is modelled on is a black silhouette with a single
   * crimson moving through it — the colour sits on the cloth, never on the skin.
   * It is a declared value rather than a free choice: `resolveInk` refuses an
   * accent that is not the one this file names unless `allowAccent` says the
   * caller knows what it is doing.
   */
  accent: '#B3151F',
};

/** Stroke widths, as a fraction of the bone that carries them. */
export const STICK = {
  spine: 0.070,
  chest: 0.066,
  neck: 0.050,
  upperArm: 0.044,
  forearm: 0.041,
  hand: 0.034,
  thigh: 0.060,
  shin: 0.055,
  foot: 0.036,
  /** Joint disc radius as a fraction of the segment's thick end. */
  joint: 0.72,
  /** Head radius as a fraction of the head bone length.
   *
   * The skeleton is about nine and a half heads tall, which reads as spindly on
   * a line figure. At 1.05 the figure is roughly seven heads — still adult, no
   * longer a stick insect.
   */
  head: 1.05,
  /** How much thinner the far-side limbs are drawn, for depth. */
  farFade: 0.92,
  /** Line-boil amplitude in design units at scale 1. */
  boilAmount: 2.2,
  /** Mouth width as a fraction of head radius. */
  mouthWidth: 0.42,
};

const DEFAULT_ACCENT = '#B3151F';

const GREY = /^#[0-9a-fA-F]{6}$/;

const isGrey = (hex) => {
  if (!GREY.test(String(hex))) return false;
  const v = String(hex).slice(1);
  return v.slice(0, 2).toLowerCase() === v.slice(2, 4).toLowerCase()
    && v.slice(2, 4).toLowerCase() === v.slice(4, 6).toLowerCase();
};

/**
 * Pick the palette, and refuse to draw in colour.
 *
 * This is the one function that makes "black and white" a guarantee rather than
 * a habit: a colour literal in a look object throws instead of quietly shipping
 * a blue stickman to a channel that asked for monochrome.
 */
export function resolveInk(opts = {}) {
  const ink = { ...INK, ...(opts.ink || {}) };
  if (!isGrey(ink.paper)) throw new Error('stick: paper must be a greyscale hex colour, got ' + ink.paper);
  if (!isGrey(ink.ink)) throw new Error('stick: ink must be a greyscale hex colour, got ' + ink.ink);
  if (!isGrey(ink.cape)) throw new Error('stick: cape must be a greyscale hex colour, got ' + ink.cape);
  if (ink.accent !== null && ink.accent !== undefined) {
    if (!GREY.test(String(ink.accent))) throw new Error('stick: accent must be a hex colour, got ' + ink.accent);
    // One accent, and only the declared one. A second colour — however tasteful —
    // is how a monochrome channel slowly stops being one.
    if (!opts.allowAccent && String(ink.accent).toLowerCase() !== String(DEFAULT_ACCENT).toLowerCase()) {
      throw new Error('stick: ' + ink.accent + ' is not the declared accent; pass allowAccent: true to override');
    }
  }
  return ink;
}

/**
 * A tiny deterministic wobble for `bone` on `frame`.
 *
 * Two independent offsets so a joint does not simply slide along one axis, and
 * a different phase per bone so neighbouring limbs do not wobble in lockstep.
 * Deterministic in (bone, frame), so a re-render of the same frame is identical.
 */
function boilOffset(bone, frame, amount, scale) {
  if (!amount) return [0, 0];
  let seed = 0;
  for (let i = 0; i < bone.length; i += 1) seed = (seed * 31 + bone.charCodeAt(i)) % 9973;
  const phase = frame * 0.85 + seed * 0.017;
  const a = Math.sin(phase) * 0.6 + Math.sin(phase * 2.37 + 1.1) * 0.4;
  const b = Math.cos(phase * 0.91 + 2.3) * 0.6 + Math.cos(phase * 1.73) * 0.4;
  const amp = amount * scale;
  return [a * amp, b * amp];
}

const width = (s, name, factor) => (s[name] ? s[name].length * factor : 0);

/** World-space geometry of the stickman, used by the drawing and by the checks. */
export function stickGeometry(solved, opts = {}) {
  const scale = solved.hips && solved.hips.scale ? solved.hips.scale : 1;
  const headRadius = solved.head ? solved.head.length * STICK.head : 0;
  return {
    scale,
    headRadius,
    widths: {
      spine: width(solved, 'spine', STICK.spine),
      chest: width(solved, 'chest', STICK.chest),
      neck: width(solved, 'neck', STICK.neck),
      upperArm: width(solved, 'armL', STICK.upperArm),
      forearm: width(solved, 'forearmL', STICK.forearm),
      hand: width(solved, 'handL', STICK.hand),
      thigh: width(solved, 'thighL', STICK.thigh),
      shin: width(solved, 'shinL', STICK.shin),
      foot: width(solved, 'footL', STICK.foot),
    },
    jointRadius: width(solved, 'armL', STICK.upperArm) * STICK.joint,
  };
}

function disc(ctx, centre, radius, colour) {
  if (radius <= 0) return;
  ctx.beginPath();
  ctx.arc(centre[0], centre[1], radius, 0, Math.PI * 2);
  ctx.fillStyle = colour;
  ctx.fill();
}

/*
 * Why the bridges exist at all: the rig places the shoulder 96 units out from
 * the spine and the hip 96 out from that, which is right for a clothed figure
 * whose torso fills the gap. A line figure has nothing to fill it, so without an
 * explicit shoulder and pelvis line the limbs float beside the body — the
 * difference between a stickman and a stack of sticks.
 */

/**
 * A curved connector: a sloping shoulder line or a rounded pelvis.
 *
 * A straight bar from spine to shoulder reads as a coat hanger. Dropping the
 * outer end by `drop` gives the line a shoulder slope, which is most of what
 * makes a figure look like it has a skeleton rather than a frame.
 */
function curvedBridge(ctx, from, to, drop, w0, w1, colour, opts) {
  const [ax, ay] = boilOffset('bridgeA', opts.frame || 0, opts.boil || 0, 1);
  const [bx, by] = boilOffset('bridgeB', opts.frame || 0, opts.boil || 0, 1);
  const p0 = [from[0] + ax, from[1] + ay];
  const p1 = [to[0] + bx, to[1] + by];
  const mid = [(p0[0] + p1[0]) / 2, (p0[1] + p1[1]) / 2 + drop];
  ctx.beginPath();
  ctx.moveTo(p0[0], p0[1]);
  ctx.quadraticCurveTo(mid[0], mid[1], p1[0], p1[1]);
  ctx.strokeStyle = colour;
  ctx.lineWidth = w0;
  ctx.lineCap = 'round';
  ctx.stroke();
  // A second pass at the root thickens the line where it meets the body, which
  // is the tapered look without needing a filled polygon along a curve.
  ctx.beginPath();
  ctx.moveTo(p0[0], p0[1]);
  ctx.quadraticCurveTo(mid[0], mid[1], (p0[0] + p1[0]) / 2, (p0[1] + p1[1]) / 2 + drop * 0.5);
  ctx.lineWidth = w1;
  ctx.stroke();
}

/** Draw one bone as a tapered stroke, offset by its boil. */
function limb(ctx, s, bone, w0, w1, colour, opts, fade = 1) {
  const b = s[bone];
  if (!b) return null;
  const [ox, oy] = boilOffset(bone, opts.frame || 0, opts.boil || 0, b.scale || 1);
  const p0 = [b.origin[0] + ox, b.origin[1] + oy];
  // The far end inherits the *parent's* direction to its child when one exists,
  // so consecutive segments meet exactly instead of overlapping by a wobble.
  const p1 = [b.end[0] + ox, b.end[1] + oy];
  taperedLimb(ctx, p0, p1, w0 * fade, w1 * fade, colour);
  return { p0, p1 };
}

function drawFace(ctx, s, ink, opts, geom) {
  const head = s.head;
  if (!head) return;
  const radius = geom.headRadius;
  const cx = head.end[0];
  const cy = head.end[1];
  // Face turns slightly with the head bone's own tilt, so a tilted head looks
  // at something rather than staring straight ahead from a leaning circle.
  const lean = Math.sin(head.world - (-Math.PI / 2)) * radius * 0.16;
  const eyeY = cy - radius * 0.10;
  const eyeDX = radius * 0.34;
  const eyeR = Math.max(1.2, radius * 0.085);
  const blink = Math.min(1, Math.max(0, opts.blink || 0));
  const faceCfg = opts.expression || {};
  // `eyeOpen` scales the eye; `squint` flattens it from below, so a hard look
  // narrows without the eye shrinking to a dot.
  const eyeOpen = Math.max(0.35, Math.min(1.5, faceCfg.eyeOpen === undefined ? 1 : faceCfg.eyeOpen));
  const squint = Math.max(0, Math.min(1, faceCfg.squint || 0));

  for (const sign of [-1, 1]) {
    const ex = cx + lean + sign * eyeDX;
    if (blink > 0.85) {
      ctx.beginPath();
      ctx.moveTo(ex - eyeR, eyeY);
      ctx.lineTo(ex + eyeR, eyeY);
      ctx.strokeStyle = ink.ink;
      ctx.lineWidth = Math.max(1, radius * 0.055);
      ctx.lineCap = 'round';
      ctx.stroke();
    } else {
      const squash = Math.max(0.06, (1 - blink * 0.85) * eyeOpen * (1 - squint * 0.55));
      const widen = 1 + squint * 0.22;
      ctx.beginPath();
      ctx.ellipse(ex, eyeY, eyeR * widen, eyeR * squash, 0, 0, Math.PI * 2);
      ctx.fillStyle = ink.ink;
      ctx.fill();
      if (squint > 0.25) {
        // A lid line over a narrowed eye. Without it a squashed ellipse reads as a
        // small dot rather than as effort.
        ctx.beginPath();
        ctx.moveTo(ex - eyeR * 1.5, eyeY - eyeR * squash * 1.15);
        ctx.lineTo(ex + eyeR * 1.5, eyeY - eyeR * squash * 1.15);
        ctx.strokeStyle = ink.ink;
        ctx.lineWidth = Math.max(1, radius * 0.05);
        ctx.lineCap = 'round';
        ctx.stroke();
      }
    }
  }

  // Brows carry the expression. Raising them lifts the whole line; angling them
  // lifts or drops the *inner* ends, which is what separates a question from a
  // challenge. A flat raised brow reads as surprise no matter what the mouth does.
  const face = opts.expression || {};
  const brow = Math.min(1, Math.max(0, opts.browRaise === undefined ? (face.brow ?? 0.2) : opts.browRaise));
  const browAngle = Math.max(-0.9, Math.min(0.9, face.browAngle || 0));
  const browY = eyeY - radius * (0.34 + brow * 0.16);
  for (const sign of [-1, 1]) {
    const bx = cx + lean + sign * eyeDX;
    // Inner end (toward the centre) moves with the angle; the outer end anchors.
    const innerLift = browAngle * radius * 0.18;
    const inner = [bx - sign * radius * 0.16, browY + innerLift];
    const outer = [bx + sign * radius * 0.15, browY - browAngle * radius * 0.04];
    ctx.beginPath();
    ctx.moveTo(inner[0], inner[1]);
    ctx.lineTo(outer[0], outer[1]);
    ctx.strokeStyle = ink.ink;
    ctx.lineWidth = Math.max(1, radius * (0.055 + brow * 0.02));
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';
    ctx.stroke();
  }

  // Mouth: a line whose opening is the viseme's `open` value, so the existing
  // lip-sync drives the drawing without knowing how a mouth is drawn.
  if (opts.mouth !== false) {
    const viseme = opts.viseme || VISEMES.REST;
    const open = Math.min(1, Math.max(0, viseme.open === undefined ? 0.12 : viseme.open));
    const wide = Math.min(1, Math.max(0, viseme.wide === undefined ? 0.5 : viseme.wide));
    // The curve is the expression; the opening is the viseme. They are separate
    // controls on purpose: a smiling face can still be mid-word.
    const smile = Math.max(-1, Math.min(1, face.smile === undefined ? 0.1 : face.smile));
    const expressionWide = face.wide === undefined ? wide : face.wide;
    const mouthY = cy + radius * (0.34 + (face.pitch || 0) * 0.08);
    const halfW = radius * STICK.mouthWidth * (0.55 + expressionWide * 0.75);
    // A smile lifts the corners; a frown pulls them down. The curve at rest is a
    // gentle line, never a flat bar.
    const cornerLift = -smile * radius * 0.13;
    const drop = radius * 0.02 + open * radius * 0.30;
    ctx.beginPath();
    ctx.moveTo(cx + lean - halfW, mouthY + cornerLift);
    ctx.quadraticCurveTo(cx + lean, mouthY + drop * 1.9 + cornerLift * 0.15,
      cx + lean + halfW, mouthY + cornerLift);
    ctx.strokeStyle = ink.ink;
    ctx.lineWidth = Math.max(1.1, radius * 0.055 + open * radius * 0.02);
    ctx.lineCap = 'round';
    ctx.stroke();
    if (open > 0.35) {
      // A filled mouth only when it is genuinely open, so the face is not a
      // permanent hole; the fill is the ink colour, never a red.
      ctx.beginPath();
      ctx.moveTo(cx + lean - halfW, mouthY + cornerLift);
      ctx.quadraticCurveTo(cx + lean, mouthY + drop * 1.9 + cornerLift * 0.15,
        cx + lean + halfW, mouthY + cornerLift);
      ctx.quadraticCurveTo(cx + lean, mouthY + drop * 0.55 + cornerLift * 0.5,
        cx + lean - halfW, mouthY + cornerLift);
      ctx.fillStyle = ink.ink;
      ctx.fill();
    }
  }
}

/** Feet: a short forward stroke with a rounded toe, planted on the ground line. */
function foot(ctx, s, bone, w, colour, opts) {
  const b = s[bone];
  if (!b) return;
  const [ox, oy] = boilOffset(bone, opts.frame || 0, opts.boil || 0, b.scale || 1);
  const ankle = [b.origin[0] + ox, b.origin[1] + oy];
  const toe = [b.end[0] + ox, b.end[1] + oy];
  taperedLimb(ctx, ankle, toe, w, w * 0.72, colour);
  disc(ctx, toe, w * 0.72, colour);
  // A heel behind the ankle. Without it the foot is a single stroke sticking out
  // of the leg, which reads as a stand rather than a foot.
  const dx = toe[0] - ankle[0];
  const dy = toe[1] - ankle[1];
  const len = Math.hypot(dx, dy) || 1;
  disc(ctx, [ankle[0] - (dx / len) * w * 1.3, ankle[1] - (dy / len) * w * 1.3], w * 0.85, colour);
}

/**
 * A hand, drawn rather than tapered away.
 *
 * The first version let the forearm taper to a point, which is the single
 * cheapest-looking thing a line figure can do: arms end in splinters. A small
 * mitten with a thumb tick costs four draw calls and reads as a hand at any size.
 */
function hand(ctx, s, bone, w, colour, opts) {
  const b = s[bone];
  if (!b) return;
  const [ox, oy] = boilOffset(bone, opts.frame || 0, opts.boil || 0, b.scale || 1);
  const wrist = [b.origin[0] + ox, b.origin[1] + oy];
  const tip = [b.end[0] + ox, b.end[1] + oy];
  // A mitt: narrow at the wrist, round at the fingers. An earlier version drew a
  // separate thumb stroke, which at video scale read as a stray hair, not a hand.
  taperedLimb(ctx, wrist, tip, w * 0.85, w * 1.5, colour);
  disc(ctx, tip, w * 1.5, colour);
}


/**
 * The cape, and the coat under it.
 *
 * A line figure has no silhouette, and a silhouette is what makes a character
 * read at a glance — the reference the channel is aiming at is built on them.
 * But a cape drawn as separate ribbons looks like ribbons: the first attempt
 * covered the chest in grey stripes. Cloth is one shape with a hem that moves.
 *
 * So: a single filled path from shoulder to shoulder, flaring out and down, with
 * a hem whose scallops drift. Motion is lag, not physics — the hem follows the
 * body with a delay, so a change of direction ripples down the cloth instead of
 * moving it all at once, and it is a pure function of the frame number.
 */
function drawCape(ctx, solved, ink, opts) {
  const chest = solved.chest;
  const spine = solved.spine;
  if (!chest || !spine) return;
  const scale = (solved.hips && solved.hips.scale) || 1;
  const frame = opts.frame || 0;
  // Cloth trails motion; it does not fly. An unclamped sway turned the cape into a
  // flag whenever the figure walked quickly (the walk-out covers 1300 px in under
  // a second, which produced a horizontal triangle).
  const sway = Math.max(-0.55, Math.min(0.55, opts.capeSway || 0));
  const lift = opts.capeLift || 0;
  const length = (opts.capeLength === undefined ? 1 : opts.capeLength) * 900 * scale;

  const shoulderY = chest.end[1] + 8 * scale;
  const shoulderHalf = Math.max(84 * scale, (Math.abs(solved.armL.origin[0] - solved.armR.origin[0]) / 2) * 0.62);
  const cx = chest.end[0];

  // The hem: a row of points, each scalloped and each lagging the one before it.
  const points = 7;
  const hem = [];
  for (let i = 0; i < points; i += 1) {
    const u = i / (points - 1);
    const side = (u - 0.5) * 2;
    const lag = 0.5 + Math.abs(side) * 0.6;
    const phase = frame * 0.05 * (0.8 + lag) + side * 1.7;
    const scallop = Math.cos(u * Math.PI * 2) * 26 * scale;
    // Cloth trails the direction the body is moving in, and lifts when the body
    // drops — the two cues that read as weight.
    const drift = sway * 150 * scale * (0.4 + Math.abs(side) * 0.9);
    const flare = shoulderHalf * (1.15 + Math.abs(side) * 1.55);
    hem.push({
      x: cx + side * flare + drift + Math.sin(phase) * 18 * scale,
      y: shoulderY + length * (0.82 + 0.18 * Math.cos(phase * 0.8)) + scallop - lift * 70 * scale,
    });
  }

  // One shape: shoulders across the top, down the outside, along the hem, back up.
  // Drawn once into a path that is kept, so the lining can be clipped to exactly
  // the same outline — following a scalloped hem with a second hand-built path
  // produced a red zigzag instead of a band.
  // `Path2D` is not available in every canvas binding this runs on (the Node one
  // used for offscreen rendering has no global constructor), so the outline is
  // traced twice through the context itself.
  const traceCape = () => {
    ctx.beginPath();
    ctx.moveTo(cx - shoulderHalf, shoulderY);
    ctx.quadraticCurveTo(cx - shoulderHalf * 1.35, shoulderY + length * 0.32, hem[0].x, hem[0].y);
    for (let i = 1; i < hem.length; i += 1) {
      const prev = hem[i - 1];
      ctx.quadraticCurveTo((prev.x + hem[i].x) / 2, (prev.y + hem[i].y) / 2 + 18 * scale,
        hem[i].x, hem[i].y);
    }
    ctx.quadraticCurveTo(cx + shoulderHalf * 1.35, shoulderY + length * 0.32,
      cx + shoulderHalf, shoulderY);
    ctx.closePath();
  };

  traceCape();
  ctx.fillStyle = ink.cape || ink.ink;
  ctx.fill();

  // The lining: the cloth clipped to its own outline, flooded over the bottom
  // band. One accent, on the moving edge of the cloth, exactly where the eye goes.
  if (ink.accent && opts.capeLining !== false) {
    // The band is positioned from the hem itself. Anchoring it to a fraction of
    // the cape's length put it below the scallops on a long cape and left a red
    // sliver at one point only.
    const hemTop = Math.min(...hem.map((point) => point.y));
    const hemBottom = Math.max(...hem.map((point) => point.y));
    const bandTop = hemBottom - (hemBottom - hemTop) * 0.85 - 70 * scale;
    ctx.save();
    traceCape();
    ctx.clip();
    ctx.fillStyle = ink.accent;
    ctx.fillRect(cx - shoulderHalf * 4, bandTop, shoulderHalf * 8, hemBottom - bandTop + 40 * scale);
    ctx.restore();
  }
}

/**
 * Draw the whole stickman.
 *
 * @param {CanvasRenderingContext2D} ctx
 * @param {object} solved solved skeleton from rig.solve()
 * @param {object} opts {ink, viseme, blink, browRaise, boil, frame, mouth, accent}
 */
export function drawStick(ctx, solved, opts = {}) {
  const ink = resolveInk(opts);
  const geom = stickGeometry(solved, opts);
  const w = geom.widths;
  const far = STICK.farFade;
  const joint = geom.jointRadius;

  ctx.save();
  ctx.lineJoin = 'round';
  ctx.lineCap = 'round';

  // Cloth first: it is behind the figure, and it is what gives the silhouette.
  if (opts.cape) drawCape(ctx, solved, ink, opts);

  // A leg that is swinging is drawn foreshortened: both segments are pulled toward
  // the hip by the same factor, so the foot leaves the floor while the knee stays
  // on its own line. Bending the knee instead would push it sideways — see the
  // note in animate.mjs — and a front-view figure has no other way to lift a foot.
  const shorten = opts.legShorten || {};
  const squash = (side) => {
    const k = shorten[side];
    return typeof k === 'number' && k > 0 && k < 1 ? k : 1;
  };
  const legView = (side) => {
    const k = squash(side);
    if (k === 1) return solved;
    const hip = solved[side === 'L' ? 'thighL' : 'thighR'];
    if (!hip) return solved;
    const anchor = hip.origin;
    const pull = (b) => (b ? { ...b,
      origin: [anchor[0] + (b.origin[0] - anchor[0]) * k, anchor[1] + (b.origin[1] - anchor[1]) * k],
      end: [anchor[0] + (b.end[0] - anchor[0]) * k, anchor[1] + (b.end[1] - anchor[1]) * k],
    } : b);
    return { ...solved,
      [side === 'L' ? 'thighL' : 'thighR']: pull(solved[side === 'L' ? 'thighL' : 'thighR']),
      [side === 'L' ? 'shinL' : 'shinR']: pull(solved[side === 'L' ? 'shinL' : 'shinR']),
      [side === 'L' ? 'footL' : 'footR']: pull(solved[side === 'L' ? 'footL' : 'footR']),
    };
  };
  const near = legView('L');
  const away = legView('R');

  // Back layer first: far arm, far leg, then the body over them, then the near
  // limbs. Drawing order is what makes the figure read as 3D without shading.
  limb(ctx, solved, 'armR', w.upperArm, w.forearm, ink.ink, opts, far);
  limb(ctx, solved, 'forearmR', w.forearm, w.hand, ink.ink, opts, far);
  hand(ctx, solved, 'handR', w.hand * far, ink.ink, opts);
  foot(ctx, away, 'footR', w.foot * far, ink.ink, opts);
  limb(ctx, away, 'thighR', w.thigh, w.shin, ink.ink, opts, far);
  limb(ctx, away, 'shinR', w.shin, w.foot, ink.ink, opts, far);

  // Body: hips → chest → neck as one continuous tapered spine.
  limb(ctx, solved, 'spine', w.spine * 1.06, w.chest, ink.ink, opts);
  limb(ctx, solved, 'chest', w.chest, w.neck, ink.ink, opts);
  limb(ctx, solved, 'neck', w.neck, w.neck * 0.9, ink.ink, opts);

  limb(ctx, near, 'thighL', w.thigh, w.shin, ink.ink, opts);
  limb(ctx, near, 'shinL', w.shin, w.foot, ink.ink, opts);
  foot(ctx, near, 'footL', w.foot, ink.ink, opts);

  // Head: an outlined circle, slightly oval, sitting on the neck.
  if (solved.head) {
    const radius = geom.headRadius;
    const cx = solved.head.end[0];
    const cy = solved.head.end[1];
    const tilt = solved.head.world + Math.PI / 2;
    ctx.save();
    ctx.translate(cx, cy);
    ctx.rotate(tilt);
    ctx.beginPath();
    // 0.96 horizontal, 1.0 vertical: a stickman head that is a perfect circle
    // reads as a helmet at 4K.
    ctx.ellipse(0, 0, radius * 0.96, radius, 0, 0, Math.PI * 2);
    ctx.fillStyle = ink.paper;
    ctx.fill();
    // The head is ink. The accent belongs to the cloth only; a red outline made
    // the face look inflamed rather than styled.
    ctx.strokeStyle = ink.ink;
    ctx.lineWidth = w.neck * 1.02;
    ctx.stroke();
    ctx.restore();
    drawFace(ctx, solved, ink, opts, geom);
  }

  // Clavicles and pelvis: the frame that turns separate limbs into a figure.
  if (solved.armL && solved.chest) {
    // Shoulders slope down and out from the base of the neck.
    const anchor = [solved.chest.end[0], solved.chest.end[1] - w.neck * 0.2];
    const drop = w.upperArm * 1.5;
    curvedBridge(ctx, anchor, solved.armL.origin, drop, w.upperArm * 0.94, w.upperArm * 1.16, ink.ink, opts);
    curvedBridge(ctx, anchor, solved.armR.origin, drop, w.upperArm * 0.9, w.upperArm * 1.1, ink.ink, opts);
  }
  if (solved.spine && solved.thighL) {
    // Pelvis: the hip band, sagging slightly so it is not a straight bar.
    const pelvisBand = w.thigh * 0.92;
    curvedBridge(ctx, solved.spine.origin, solved.thighL.origin, w.thigh * 0.42, pelvisBand, w.thigh * 1.05, ink.ink, opts);
    curvedBridge(ctx, solved.spine.origin, solved.thighR.origin, w.thigh * 0.42, pelvisBand, w.thigh * 1.05, ink.ink, opts);
  }

  // Near arm last so it sits over the torso.
  limb(ctx, solved, 'armL', w.upperArm, w.forearm, ink.ink, opts);
  limb(ctx, solved, 'forearmL', w.forearm, w.hand, ink.ink, opts);
  hand(ctx, solved, 'handL', w.hand, ink.ink, opts);

  // Joints: hips, shoulders, elbows, knees. Drawn after the limbs so they cap
  // the joins instead of being hidden under the strokes.
  const joints = [
    ['hips', joint * 1.25],
    ['chest', joint * 0.85],
    ['neck', joint * 0.55],
    ['armL', joint * 0.78], ['forearmL', joint * 0.66],
    ['armR', joint * 0.78], ['forearmR', joint * 0.66],
    ['thighL', joint * 0.88], ['shinL', joint * 0.74],
    ['thighR', joint * 0.88], ['shinR', joint * 0.74],
  ];
  const jointView = { ...solved, ...{ thighL: near.thighL, shinL: near.shinL, thighR: away.thighR, shinR: away.shinR } };
  for (const [bone, radius] of joints) {
    const b = jointView[bone];
    if (!b) continue;
    const [ox, oy] = boilOffset(bone, opts.frame || 0, opts.boil || 0, b.scale || 1);
    disc(ctx, [b.origin[0] + ox, b.origin[1] + oy], radius, ink.ink);
  }

  ctx.restore();
  return geom;
}
